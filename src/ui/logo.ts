/** 字模缺失时留空白,永远不抛错——logo 画不出来不该拖垮整个横幅。 */
function glyphOf(ch: string): readonly string[] {
  return FONT[ch.toUpperCase()] ?? BLANK;
}

/**
 * 把文本渲染成像素字。返回 3 行,每行按输入字符切成若干段(段内含右侧间隙,
 * 末字符除外)——切段是为了让调用方能逐字上色做渐变;整行一个字符串就只能
 * 一种颜色。
 */
export function renderPixelLogo(text: string): string[][] {
  const chars = [...text];
  const rows: string[][] = [];
  for (let y = 0; y < GLYPH_H; y += 2) {
    const row: string[] = [];
    chars.forEach((ch, i) => {
      const g = glyphOf(ch);
      let seg = '';
      for (let x = 0; x < GLYPH_W; x++) {
        // 上下两行像素合成一个字符格:全亮 █,只有上半 ▀,只有下半 ▄。
        // y+1 越界(奇数行高的最后一行)按熄灭处理,自然只画上半格。
        const top = g[y]?.[x] === '#';
        const bottom = g[y + 1]?.[x] === '#';
        seg += top && bottom ? '█' : top ? '▀' : bottom ? '▄' : ' ';
      }
      if (i < chars.length - 1) seg += ' '.repeat(GAP);
      row.push(seg);
    });
    rows.push(row);
  }
  return rows;
}

/** 像素字占的列数。调用方据此决定画 logo 还是退回纯文字。 */
export function pixelLogoWidth(text: string): number {
  const n = [...text].length;
  return n <= 0 ? 0 : n * GLYPH_W + (n - 1) * GAP;
}

/**
 * logo 的横向渐变色。端点刻意留在 accent(cyan)同族里——从青绿滑到靛蓝,
 * 与主题里其它青色是一家人,不至于让首屏冒出一块无关的品牌色。
 */
const FROM = [0x5e, 0xea, 0xd4] as const;
const TO = [0x81, 0x8c, 0xf8] as const;

export function logoGradient(n: number): string[] {
  if (n <= 0) return [];
  if (n === 1) return [hex(FROM)];
  return Array.from({ length: n }, (_, i) => {
    const k = i / (n - 1);
    return hex([0, 1, 2].map((c) => Math.round(FROM[c]! + (TO[c]! - FROM[c]!) * k)));
  });
}

function hex(rgb: readonly number[]): string {
  return `#${rgb.map((v) => v.toString(16).padStart(2, '0')).join('')}`;
}
