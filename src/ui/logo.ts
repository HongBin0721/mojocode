/**
 * 启动横幅上的像素字 logo。
 *
 * 5×5 点阵字模 + 半块字符(▀ ▄ █)把两行像素压进一行文本:5 行像素 → 3 行
 * 文本。终端字符格大约是 1:2 的长宽比,压完之后每个"像素"接近正方形,看着
 * 才像像素画,而不是被拉扁的横幅字。三行的高度也刚好——五行的全块大字会把
 * 首屏的对话内容顶下去。
 *
 * 字模用 '#'/'.' 而不是 '█'/' ' 书写:点阵在源码里一眼可读,且行尾不带空格,
 * 不会被编辑器/格式化工具悄悄裁掉导致字形缺列。
 */

/** 单个字模的像素宽/高,以及字与字之间的间隙(列)。 */
const GLYPH_W = 5;
const GLYPH_H = 5;
const GAP = 1;

const BLANK = ['.....', '.....', '.....', '.....', '.....'] as const;

